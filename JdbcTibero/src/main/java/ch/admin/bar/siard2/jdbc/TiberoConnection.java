package ch.admin.bar.siard2.jdbc;

import ch.enterag.utils.jdbc.BaseConnection;

import java.sql.Array;
import java.sql.Connection;
import java.sql.DatabaseMetaData;
import java.sql.PreparedStatement;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.regex.Pattern;

/**
 * Tibero 연결 래퍼.
 *
 * <p>메타데이터와 문장을 래퍼로 감싸고, 배열 지원 검사에 쓰는 원소 타입 이름을 Tibero 표기로 바꾼다.
 * SQL 번역({@link #nativeSQL})은 1단계에서 입력을 그대로 돌려준다. 현행 추출 경로가 통과 방식으로
 * 확인되었으므로 동작이 바뀌지 않는다. 2단계에서 방언 팩토리를 붙인다.
 */
public class TiberoConnection extends BaseConnection {

    /** 제약 없는 NUMBER 컬럼을 재는 일. 같은 컬럼을 두 번 재지 않도록 연결마다 하나 둔다. */
    private final TiberoNumberMeasure _numberMeasure = new TiberoNumberMeasure(this);
    /** 문자 의미 컬럼의 선언 길이. 같은 테이블을 두 번 읽지 않도록 연결마다 하나 둔다. */
    private final TiberoCharLength _charLength = new TiberoCharLength(this);

    public TiberoConnection(Connection connNative) {
        super(connNative);
    }

    TiberoNumberMeasure numberMeasure() {
        return _numberMeasure;
    }

    TiberoCharLength charLength() {
        return _charLength;
    }

    /** 엔진의 LOB 크기 질의가 쓰는 표준 함수. Tibero 에는 없다(JDBC-8086, 2026-09-08 실측). */
    private static final Pattern _patOctetLength = Pattern.compile("\\bOCTET_LENGTH\\s*\\(", Pattern.CASE_INSENSITIVE);

    /**
     * {@inheritDoc} 1단계: 문장을 그대로 통과시킨다. 예외는 하나다. 엔진이 외부 LOB 폴더(-x) 결정에 쓰는
     * 크기 질의 {@code SUM(OCTET_LENGTH(col))}의 OCTET_LENGTH 를 Tibero 가 지원하지 않으므로
     * {@code DBMS_LOB.GETLENGTH} 로 바꾼다. CLOB 은 문자 수, BLOB 은 바이트 수를 돌려주는 근사치다.
     * 다른 제품 래퍼는 방언 팩토리가 같은 일을 한다. 벤더 드라이버의 nativeSQL 은 부르지 않는다(현행 동작 유지).
     */
    @Override
    public String nativeSQL(String sql) {
        if (sql == null) {
            return null;
        }
        return _patOctetLength.matcher(sql).replaceAll("DBMS_LOB.GETLENGTH(");
    }

    @Override
    public DatabaseMetaData getMetaData() throws SQLException {
        return new TiberoDatabaseMetaData(super.getMetaData(), this);
    }

    @Override
    public Statement createStatement() throws SQLException {
        return new TiberoStatement(super.createStatement(), this);
    }

    @Override
    public Statement createStatement(int resultSetType, int resultSetConcurrency) throws SQLException {
        return new TiberoStatement(super.createStatement(resultSetType, resultSetConcurrency), this);
    }

    @Override
    public Statement createStatement(int resultSetType, int resultSetConcurrency, int resultSetHoldability)
            throws SQLException {
        return new TiberoStatement(
                super.createStatement(resultSetType, resultSetConcurrency, resultSetHoldability), this);
    }

    @Override
    public PreparedStatement prepareStatement(String sql) throws SQLException {
        return super.prepareStatement(nativeSQL(sql));
    }

    @Override
    public PreparedStatement prepareStatement(String sql, int resultSetType, int resultSetConcurrency)
            throws SQLException {
        return super.prepareStatement(nativeSQL(sql), resultSetType, resultSetConcurrency);
    }

    @Override
    public PreparedStatement prepareStatement(String sql, int resultSetType, int resultSetConcurrency,
                                              int resultSetHoldability) throws SQLException {
        return super.prepareStatement(nativeSQL(sql), resultSetType, resultSetConcurrency, resultSetHoldability);
    }

    @Override
    public PreparedStatement prepareStatement(String sql, int autoGeneratedKeys) throws SQLException {
        return super.prepareStatement(nativeSQL(sql), autoGeneratedKeys);
    }

    @Override
    public PreparedStatement prepareStatement(String sql, int[] columnIndexes) throws SQLException {
        return super.prepareStatement(nativeSQL(sql), columnIndexes);
    }

    @Override
    public PreparedStatement prepareStatement(String sql, String[] columnNames) throws SQLException {
        return super.prepareStatement(nativeSQL(sql), columnNames);
    }

    /**
     * {@inheritDoc} 배열 원소 타입 이름을 Tibero 표기로 바꾼다. 엔진의 배열 지원 검사는 표준 이름
     * {@code INTEGER}를 넘기고, Tibero는 {@code INTEGER_OBJ}를 요구한다.
     */
    @Override
    public Array createArrayOf(String typeName, Object[] elements) throws SQLException {
        return super.createArrayOf(toTiberoArrayElementType(typeName), elements);
    }

    static String toTiberoArrayElementType(String typeName) {
        if ("INTEGER".equalsIgnoreCase(typeName)) {
            return "INTEGER_OBJ";
        }
        return typeName;
    }
}

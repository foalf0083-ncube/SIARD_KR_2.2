package ch.admin.bar.siard2.jdbc;

import ch.enterag.utils.jdbc.BaseStatement;

import java.sql.Connection;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;

/**
 * Tibero 문장 래퍼. 실행 SQL은 연결의 {@link TiberoConnection#nativeSQL}을 거치고
 * 결과집합은 {@link TiberoResultSet}으로 감싼다.
 */
public class TiberoStatement extends BaseStatement {

    private final TiberoConnection _conn;

    public TiberoStatement(Statement stmtWrapped, TiberoConnection conn) throws SQLException {
        super(stmtWrapped);
        _conn = conn;
    }

    @Override
    public Connection getConnection() {
        return _conn;
    }

    private ResultSet wrap(ResultSet rs) {
        return (rs == null) ? null : new TiberoResultSet(rs, _conn, this);
    }

    @Override
    public ResultSet executeQuery(String sql) throws SQLException {
        return wrap(super.executeQuery(_conn.nativeSQL(sql)));
    }

    @Override
    public int executeUpdate(String sql) throws SQLException {
        return super.executeUpdate(_conn.nativeSQL(sql));
    }

    @Override
    public int executeUpdate(String sql, int autoGeneratedKeys) throws SQLException {
        return super.executeUpdate(_conn.nativeSQL(sql), autoGeneratedKeys);
    }

    @Override
    public int executeUpdate(String sql, int[] columnIndexes) throws SQLException {
        return super.executeUpdate(_conn.nativeSQL(sql), columnIndexes);
    }

    @Override
    public int executeUpdate(String sql, String[] columnNames) throws SQLException {
        return super.executeUpdate(_conn.nativeSQL(sql), columnNames);
    }

    @Override
    public boolean execute(String sql) throws SQLException {
        return super.execute(_conn.nativeSQL(sql));
    }

    @Override
    public boolean execute(String sql, int autoGeneratedKeys) throws SQLException {
        return super.execute(_conn.nativeSQL(sql), autoGeneratedKeys);
    }

    @Override
    public boolean execute(String sql, int[] columnIndexes) throws SQLException {
        return super.execute(_conn.nativeSQL(sql), columnIndexes);
    }

    @Override
    public boolean execute(String sql, String[] columnNames) throws SQLException {
        return super.execute(_conn.nativeSQL(sql), columnNames);
    }

    @Override
    public ResultSet getResultSet() throws SQLException {
        return wrap(super.getResultSet());
    }
}
